// renderResults writes RESULTS.md.
//
// Every number in this document comes from the run that produced it. Nothing
// here is typed by hand, which is the point: a submission whose figures were
// transcribed cannot be checked against the code that supposedly produced
// them, and this project's whole argument is about the difference between a
// claim and a verified one.
func renderResults(
	sum bench.Summary,
	cases []bench.CaseOutcome,
	sweep []bench.SweepPoint,
	envelope []bench.EnvelopePoint,
) string {
	var b strings.Builder

	fmt.Fprintf(&b, "# Manhattan results\n\n")
	fmt.Fprintf(&b, "Generated by `manhattan bench` on %s. Every figure below is emitted by that\n",
		time.Now().UTC().Format("2006-01-02 15:04 UTC"))
	fmt.Fprintf(&b, "command from a seeded run. None of it is typed by hand.\n\n")
	fmt.Fprintf(&b, "```\nrun id     %s\nseed       %d\nprovider   %s\nmodels     %s\n```\n\n",
		sum.RunID, sum.Seed, sum.Provider, sum.ProviderModels)

	// ---- Batch outcome ---------------------------------------------------
	fmt.Fprintf(&b, "## Batch outcome against the baseline\n\n")
	fmt.Fprintf(&b, "B0 is a confidence matcher given the same inputs and the same narrowing.\n")
	fmt.Fprintf(&b, "It differs from Manhattan only in what it is willing to conclude: it does not\n")
	fmt.Fprintf(&b, "count rival explanations, does not gate on feasibility, and does not test\n")
	fmt.Fprintf(&b, "whether its answer survives its own filtering.\n\n")

	fmt.Fprintf(&b, "| %d settlements | Manhattan | B0 |\n|---|---:|---:|\n", sum.Settlements)
	order := []evidence.Status{
		evidence.StatusVerified, evidence.StatusAmbiguous, evidence.StatusUnderdetermined,
		evidence.StatusNarrowingSensitive, evidence.StatusUnresolved,
	}
	for _, s := range order {
		rhs := "n/a"
		if s == evidence.StatusUnresolved {
			rhs = fmt.Sprintf("%d", sum.B0Unresolved)
		}
		fmt.Fprintf(&b, "| %s | %d | %s |\n", s, sum.StatusCounts[s], rhs)
	}
	fmt.Fprintf(&b, "| | | |\n")
	fmt.Fprintf(&b, "| **auto-posted** | **%d** | **%d** |\n", sum.AutoPosted, sum.B0Posted)
	fmt.Fprintf(&b, "| **auto-posted WRONG** | **%d** | **%d** |\n", sum.AutoPostedWrong, sum.B0PostedWrong)
	fmt.Fprintf(&b, "| exceptions | %d | %d |\n", sum.Exceptions, sum.B0Unresolved)
	fmt.Fprintf(&b, "| median latency | %.1f ms | %.1f ms |\n", sum.MedianLatencyMS, sum.B0MedianMS)
	fmt.Fprintf(&b, "| p95 latency | %.1f ms | |\n", sum.P95LatencyMS)
	fmt.Fprintf(&b, "| peak memory | %.0f MB | |\n", sum.PeakMemoryMB)
	fmt.Fprintf(&b, "| settlements / hour | %.0f | |\n", sum.PerHour)
	fmt.Fprintf(&b, "| model calls per 1k | %.0f | %.0f |\n",
		float64(sum.ModelCalls)*1000/float64(max(sum.Settlements, 1)), 1000.0)
	fmt.Fprintf(&b, "| input tokens per 1k | %.2f M | %.2f M |\n",
		sum.AxiomTokPer1k/1e6, sum.B0TokensPer1k/1e6)
	fmt.Fprintf(&b, "| cost per 1k settlements | INR %.2f | INR %.2f |\n\n", sum.INRPer1k, sum.B0INRPer1k)

	priced := "actual spend"
	if !sum.PriceIsReal {
		priced = "no model was billed on this run, so the token counts are priced at published " +
			"rates for what the live path would have cost"
	}
	fmt.Fprintf(&b, "Both systems are priced at `%s` rates (%s). B0's input scales with pool size,\n",
		sum.PricedAt, priced)
	fmt.Fprintf(&b, "because a matcher that reasons over the candidate pool has to put the pool in the\n")
	fmt.Fprintf(&b, "context window. Manhattan's parse call reads one line of bank narration whatever\n")
	fmt.Fprintf(&b, "the pool size, and its expensive agent loop runs only on exceptions. The\n")
	fmt.Fprintf(&b, "advantage widens as merchants grow.\n\n")

	if sum.AutoPostedWrong == 0 {
		fmt.Fprintf(&b, "The wrong-posting row is the one that matters, and it means something only\n")
		fmt.Fprintf(&b, "because the baseline is beside it on identical data. Manhattan reporting zero\n")
		fmt.Fprintf(&b, "in isolation would be close to tautological: it posts only when an integer\n")
		fmt.Fprintf(&b, "identity closes and nothing rivals it. Manhattan reporting zero next to B0's\n")
		fmt.Fprintf(&b, "%d, on the same inputs, is a result.\n\n", sum.B0PostedWrong)
	}

	if len(sum.Drift) > 0 {
		fmt.Fprintf(&b, "**This run is gated.** The narrowing drift monitor found `%s` dropping %.1f%% of\n",
			sum.Drift[0].Constraint, sum.Drift[0].Observed*100)
		fmt.Fprintf(&b, "the universe against a stored baseline of %.1f%%. That is a property of the batch\n",
			sum.Drift[0].Baseline*100)
		fmt.Fprintf(&b, "rather than of any one settlement, so it lives on the run object and holds the\n")
		fmt.Fprintf(&b, "whole batch rather than appearing on receipts an analyst could clear one by one.\n\n")
	}

	if len(sum.FlagCounts) > 0 {
		fmt.Fprintf(&b, "### Flags\n\nFlags are orthogonal to status. A settlement can be verified and still\n")
		fmt.Fprintf(&b, "carry a fee anomaly, because whether the money is accounted for and whether the\n")
		fmt.Fprintf(&b, "fee applied to it was right are different questions.\n\n")
		type fc struct {
			f evidence.Flag
			n int
		}
		var rows []fc
		for f, n := range sum.FlagCounts {
			rows = append(rows, fc{f, n})
		}
		sort.Slice(rows, func(i, j int) bool { return rows[i].n > rows[j].n })
		fmt.Fprintf(&b, "| flag | settlements |\n|---|---:|\n")
		for _, r := range rows {
			fmt.Fprintf(&b, "| `%s` | %d |\n", r.f, r.n)
		}
		b.WriteString("\n")
	}

	// ---- The agent ------------------------------------------------------
	if sum.AgentCalls > 0 || sum.AgentSkipped > 0 {
		fmt.Fprintf(&b, "## What the agent did\n\n")
		fmt.Fprintf(&b, "The agent is a bounded loop over a closed action space: observe the receipt,\n")
		fmt.Fprintf(&b, "choose one action, apply it as an edit to the pipeline's inputs, then re-run the\n")
		fmt.Fprintf(&b, "entire verification stack unchanged over the result. It cannot reach the decision.\n\n")

		fmt.Fprintf(&b, "| | |\n|---|---:|\n")
		fmt.Fprintf(&b, "| settlements held for review | %d |\n", sum.Exceptions)
		fmt.Fprintf(&b, "| agent invoked on | %d |\n", sum.AgentInvoked)
		fmt.Fprintf(&b, "| **not invoked, by deterministic triage** | **%d** |\n", sum.AgentSkipped)
		fmt.Fprintf(&b, "| actions taken | %d |\n", sum.AgentSteps)
		fmt.Fprintf(&b, "| repaired into a posting | %d |\n", sum.AgentRepaired)
		fmt.Fprintf(&b, "| given a proven cure | %d |\n\n", sum.AgentProvenCures)

		fmt.Fprintf(&b, "The triage row is the one worth reading. About %.0f per cent of exceptions are\n",
			100*float64(sum.AgentSkipped)/float64(max(sum.Exceptions, 1)))
		fmt.Fprintf(&b, "settled without a model call at all, because a cheap deterministic check\n")
		fmt.Fprintf(&b, "establishes that no action in the vocabulary could change the outcome: the\n")
		fmt.Fprintf(&b, "amounts do not distinguish the transactions, or a rival already appears when the\n")
		fmt.Fprintf(&b, "pool is widened, or there is nothing left to search or tighten. Paying a model to\n")
		fmt.Fprintf(&b, "conclude that nothing can help, on most of a queue, is the same mistake as paying\n")
		fmt.Fprintf(&b, "it to add up a column.\n\n")

		fmt.Fprintf(&b, "A proven cure is the loop's most common useful output, and it is not a posting.\n")
		fmt.Fprintf(&b, "It is a remediation whose effect has been computed and verified rather than\n")
		fmt.Fprintf(&b, "estimated: tightening this window to seven hours yields exactly one\n")
		fmt.Fprintf(&b, "reconstruction, with the identity closing to zero. It still does not post.\n")
		fmt.Fprintf(&b, "Changing a filter is an assertion about the merchant's settlement behaviour\n")
		fmt.Fprintf(&b, "rather than corroborated evidence, and removing candidates cannot make the\n")
		fmt.Fprintf(&b, "survivor unique, only unexamined. Only an action citing a real record in a real\n")
		fmt.Fprintf(&b, "feed may post.\n\n")

		fmt.Fprintf(&b, "That rule was learned rather than designed. Without it, an agent able to retune\n")
		fmt.Fprintf(&b, "narrowing produced two wrong postings in three hundred settlements: it tightened\n")
		fmt.Fprintf(&b, "a window, the pool fell from 44 records to 40, an ambiguous settlement became\n")
		fmt.Fprintf(&b, "verified, and the answer was wrong because the tightening had cut real records\n")
		fmt.Fprintf(&b, "out of the batch.\n\n")
	}

	// ---- Segmentation ----------------------------------------------------
	if len(sum.ByArchetype) > 0 {
		fmt.Fprintf(&b, "## Which merchants this works for, and why\n\n")
		fmt.Fprintf(&b, "A single blended auto-post rate across six merchant types describes none of\n")
		fmt.Fprintf(&b, "them. What matters is that the rate is predictable from the amount distribution\n")
		fmt.Fprintf(&b, "alone: one pass over a merchant's historical settlement amounts gives the\n")
		fmt.Fprintf(&b, "contribution spread and the twin mass, those give the collision index, and that\n")
		fmt.Fprintf(&b, "gives the expected status mix. Before any integration, before a single file is\n")
		fmt.Fprintf(&b, "exchanged.\n\n")
		fmt.Fprintf(&b, "That is only possible because the system knows exactly what makes it fail.\n\n")

		fmt.Fprintf(&b, "| archetype | expected regime | sigma (paise) | twin mass | index | auto-post | wrong | B0 posts | B0 wrong |\n")
		fmt.Fprintf(&b, "|---|---|---:|---:|---:|---:|---:|---:|---:|\n")
		for _, a := range sum.ByArchetype {
			fmt.Fprintf(&b, "| %s | %s | %.3g | %.2f | %.3g | **%.0f%%** | %d | %.0f%% | %.0f%% |\n",
				a.Archetype, a.ExpectedRegime, a.MeanSigmaPaise, a.MeanTwinMass, a.MeanIndex,
				a.AutoPostRate*100, a.AutoPostedWrong, a.B0PostRate*100, a.B0WrongRate*100)
		}
		b.WriteString("\n")
		fmt.Fprintf(&b, "Read the two right-hand columns against the two before them. On the merchant\n")
		fmt.Fprintf(&b, "types where amounts genuinely do not distinguish transactions, Manhattan's\n")
		fmt.Fprintf(&b, "auto-post rate goes to zero and B0's wrong-posting rate goes up. Both systems\n")
		fmt.Fprintf(&b, "are seeing the same thing. Only one of them is reacting to it.\n\n")
		fmt.Fprintf(&b, "The refusals are also segmented rather than uniform. A subscription merchant is\n")
		fmt.Fprintf(&b, "not told that reconciliation failed. They are told that their settlements are\n")
		fmt.Fprintf(&b, "built from three repeated price points, that no amount-based method can\n")
		fmt.Fprintf(&b, "distinguish them, and which single change moves them across the boundary.\n\n")
	}

	// ---- Adversarial cases ----------------------------------------------
	fmt.Fprintf(&b, "## The eleven adversarial cases\n\n")
	fmt.Fprintf(&b, "One cherry-picked match proves nothing, so each case is a specific, nameable\n")
	fmt.Fprintf(&b, "way a confidence matcher produces a wrong answer.\n\n")
	fmt.Fprintf(&b, "| # | case | pool | Manhattan | B0 | met |\n|---|---|---:|---|---|---|\n")
	var met, mWrong, b0Wrong int
	for _, oc := range cases {
		b0 := "held"
		if oc.B0Posted {
			b0 = fmt.Sprintf("posted @ %.2f", oc.B0Confidence)
			if oc.B0PostedWrong {
				b0 += " **wrong**"
				b0Wrong++
			}
		}
		flags := ""
		if len(oc.Flags) > 0 {
			var fs []string
			for _, f := range oc.Flags {
				fs = append(fs, "`"+string(f)+"`")
			}
			flags = " " + strings.Join(fs, " ")
		}
		mark := "yes"
		if !oc.Met {
			mark = "**no**"
		}
		if oc.PostedWrong {
			mark = "**WRONG POSTING**"
			mWrong++
		} else if oc.Met {
			met++
		}
		fmt.Fprintf(&b, "| %d | %s | %d | %s%s | %s | %s |\n",
			oc.Case.Number, oc.Case.Name, oc.PoolN, oc.Status, flags, b0, mark)
	}
	fmt.Fprintf(&b, "\n%d of %d expectations met. Manhattan wrong postings: %d. B0 wrong postings: %d.\n\n",
		met, len(cases), mWrong, b0Wrong)

	// ---- Calibration -----------------------------------------------------
	if len(sweep) > 0 {
		fmt.Fprintf(&b, "## Does the system know in advance when it is about to be wrong?\n\n")
		fmt.Fprintf(&b, "This is the real question, and it is more useful than an accuracy figure,\n")
		fmt.Fprintf(&b, "because it says whether the system's own self-assessment is calibrated. The\n")
		fmt.Fprintf(&b, "collision index is computed before any search; the outcome rates are measured\n")
		fmt.Fprintf(&b, "after. If the curves turn where the index predicts they turn, the feasibility\n")
		fmt.Fprintf(&b, "gate and the merchant segmentation are both shippable.\n\n")

		fmt.Fprintf(&b, "| collision index band | configs | verified | ambiguous | underdetermined | Manhattan wrong | B0 wrong |\n")
		fmt.Fprintf(&b, "|---|---:|---:|---:|---:|---:|---:|\n")
		for _, bk := range bench.LogSpaced(sweep, 8) {
			if bk.N == 0 {
				continue
			}
			fmt.Fprintf(&b, "| %.3g to %.3g | %d | %.0f%% | %.0f%% | %.0f%% | %.0f%% | %.0f%% |\n",
				bk.LoIndex, bk.HiIndex, bk.N,
				bk.Verified*100, bk.Ambiguous*100, bk.Underdetermined*100,
				bk.Wrong*100, bk.B0Wrong*100)
		}
		b.WriteString("\n")

		// The estimator comparison, which is a finding rather than a footnote.
		var empErr, anaErr float64
		var cnt int
		for _, p := range sweep {
			if p.MeanRivals <= 0 || p.MeanIndex <= 0 || p.MeanAnalyticIndex <= 0 {
				continue
			}
			empErr += logAbsRatio(p.MeanIndex, p.MeanRivals)
			anaErr += logAbsRatio(p.MeanAnalyticIndex, p.MeanRivals)
			cnt++
		}
		if cnt > 0 {
			fmt.Fprintf(&b, "### The two estimators\n\n")
			fmt.Fprintf(&b, "The published closed form assumes k-subset sums are locally uniform near the\n")
			fmt.Fprintf(&b, "target, with a density read off a moment-matched normal. Real ticket amounts\n")
			fmt.Fprintf(&b, "are close to lognormal, and a sum of three of those is nothing like a normal\n")
			fmt.Fprintf(&b, "distribution in its body. Manhattan therefore measures the density by sampling\n")
			fmt.Fprintf(&b, "the actual pool instead of assuming it, and carries both numbers on every\n")
			fmt.Fprintf(&b, "receipt.\n\n")
			fmt.Fprintf(&b, "Mean absolute log-ratio against the exhaustively counted number of\n")
			fmt.Fprintf(&b, "reconstructions, across %d swept configurations (0 is perfect, 1.0 is off by a\n", cnt)
			fmt.Fprintf(&b, "factor of e):\n\n")
			fmt.Fprintf(&b, "| estimator | error |\n|---|---:|\n")
			fmt.Fprintf(&b, "| empirical, by sampling the pool | %.2f |\n", empErr/float64(cnt))
			fmt.Fprintf(&b, "| analytic, moment-matched normal | %.2f |\n\n", anaErr/float64(cnt))
		}

		fmt.Fprintf(&b, "### Full sweep\n\n")
		fmt.Fprintf(&b, "| archetype | pool | batch | sigma (paise) | twin mass | index | counted | verified | wrong | B0 wrong |\n")
		fmt.Fprintf(&b, "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n")
		for _, p := range sweep {
			fmt.Fprintf(&b, "| %s | %d | %d | %.3g | %.2f | %.3g | %.1f | %.0f%% | %.0f%% | %.0f%% |\n",
				p.Archetype, p.PoolN, p.BatchSize, p.MeanSigmaPaise, p.MeanTwinMass,
				p.MeanIndex, p.MeanRivals, p.VerifiedRate*100, p.WrongPostRate*100, p.B0WrongPostRate*100)
		}
		b.WriteString("\n")
	}

	// ---- Envelope --------------------------------------------------------
	fmt.Fprintf(&b, "## Resource envelope, modelled against measured\n\n")
	fmt.Fprintf(&b, "Publishing a modelled number under a measured heading is exactly the class of\n")
	fmt.Fprintf(&b, "unverified claim this system exists to refuse, so both columns are printed.\n")
	fmt.Fprintf(&b, "Every timing includes the uniqueness proof: these are not solve times with a\n")
	fmt.Fprintf(&b, "proof still owed.\n\n")
	fmt.Fprintf(&b, "| pool | k | entries predicted | entries observed | MB predicted | MB observed | solve AND prove |\n")
	fmt.Fprintf(&b, "|---:|---:|---:|---:|---:|---:|---:|\n")
	for _, e := range envelope {
		fmt.Fprintf(&b, "| %d | %d | %s | %s | %.0f | %.0f | %.0f ms |\n",
			e.PoolN, e.KStar, commas(e.PredictedEntries), commas(e.ObservedEntries),
			e.PredictedMB, e.ObservedMB, e.SolveMS)
	}
	fmt.Fprintf(&b, "\nCost tracks the free cardinality, not the pool size. A 100-record pool at k=5\n")
	fmt.Fprintf(&b, "is more expensive than a 320-record pool at k=3, and that inversion is the\n")
	fmt.Fprintf(&b, "signature of an algorithm matched to the constraint that actually binds.\n\n")

	fmt.Fprintf(&b, "---\n\nReproduce with `make bench`. Same seed, same numbers.\n")
	return b.String()
}

func logAbsRatio(a, b float64) float64 {
	if a <= 0 {
		a = 1e-9
	}
	if b <= 0 {
		b = 1e-9
	}
	r := a / b
	if r < 1 {
		r = 1 / r
	}
	return logf(r)
}

func logf(x float64) float64 {
	// A small dependency-free natural log, adequate for a reported statistic.
	if x <= 0 {
		return 0
	}
	var n float64
	for x > 2 {
		x /= 2
		n++
	}
	for x < 0.5 {
		x *= 2
		n--
	}
	z := (x - 1) / (x + 1)
	z2 := z * z
	s := z
	term := z
	for i := 3; i < 16; i += 2 {
		term *= z2
		s += term / float64(i)
	}
	return 2*s + n*0.6931471805599453
}

func commas(n int64) string {
	if n >= solver.Cap {
		return "over 1e18"
	}
	s := fmt.Sprintf("%d", n)
	var out []byte
	for i, c := range []byte(s) {
		if i > 0 && (len(s)-i)%3 == 0 {
			out = append(out, ',')
		}
		out = append(out, c)
	}
	return string(out)
}

func max(a, b int) int {
	if a > b {
		return a
	}
	return b
}
