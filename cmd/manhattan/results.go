// cell renders a sentence into a markdown table cell without breaking it.
func cell(s string, n int) string {
	s = strings.TrimSpace(strings.ReplaceAll(s, "|", "/"))
	if len(s) <= n {
		return s
	}
	cut := strings.LastIndex(s[:n], " ")
	if cut < n/2 {
		cut = n
	}
	return s[:cut] + "..."
}

// monoWord reports whether a band's verified rate falls monotonically as the
// predicted index rises.
func monoWord(ok bool) string {
	if ok {
		return "**monotone**"
	}
	return "not monotone"
}

// intList renders a small set of cardinalities as prose.
func intList(xs []int) string {
	switch len(xs) {
	case 0:
		return "none"
	case 1:
		return fmt.Sprintf("%d", xs[0])
	case 2:
		return fmt.Sprintf("%d and %d", xs[0], xs[1])
	}
	var out string
	for i, x := range xs[:len(xs)-1] {
		if i > 0 {
			out += ", "
		}
		out += fmt.Sprintf("%d", x)
	}
	return out + fmt.Sprintf(" and %d", xs[len(xs)-1])
}

func logAbsRatio(a, b float64) float64 {
	if a <= 0 {
		a = 1e-9
	}
	if b <= 0 {
		b = 1e-9
	}
	r := a / b
	if r < 1 {
		r = 1 / r
	}
	return logf(r)
}

func logf(x float64) float64 {
	// A small dependency-free natural log, adequate for a reported statistic.
	if x <= 0 {
		return 0
	}
	var n float64
	for x > 2 {
		x /= 2
		n++
	}
	for x < 0.5 {
		x *= 2
		n--
	}
	z := (x - 1) / (x + 1)
	z2 := z * z
	s := z
	term := z
	for i := 3; i < 16; i += 2 {
		term *= z2
		s += term / float64(i)
	}
	return 2*s + n*0.6931471805599453
}

func commas(n int64) string {
	if n >= solver.Cap {
		return "over 1e18"
	}
	// A negative number rendered by grouping its digits from the right puts a
	// separator immediately after the sign, which is how "-105236" became
	// "-,105,236" in a published table.
	if n < 0 {
		return "-" + commas(-n)
	}
	s := fmt.Sprintf("%d", n)
	var out []byte
	for i, c := range []byte(s) {
		if i > 0 && (len(s)-i)%3 == 0 {
			out = append(out, ',')
		}
		out = append(out, c)
	}
	return string(out)
}

func max(a, b int) int {
	if a > b {
		return a
	}
	return b
}
